export const accRest = (t, kind) => (kind === 'c' ? (t === 'R' ? 90 : 120) : 60)
export const estMinutes = (day, t) => {
  const n = TYPES[t].sets
  let total = 6 + (day.lift ? n * (0.75 + TYPES[t].rest / 60) : 0)
  day.acc.forEach(([, k]) => (total += n * (0.75 + accRest(t, k) / 60)))
  return Math.round(total)
}
